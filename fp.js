function renderPlanetCard(planet) {
  const meta = PLANET_META[planet.name] || { image: "", blurb: "" };

  // [label, value, isDerived]
  const rows = [
    ["Position from the Sun", planet.order + " of 8", false],
    ["Diameter", fmt(planet.diameter_km) + " km", false],
    ["Mass", planet.mass_vs_earth + " × Earth", false],
    ["Distance from the Sun", planet.distance_au + " AU", false],
    ["Average temperature", fmt(planet.avg_temp_c) + " °C ("
                            + fmt(planet.avg_temp_f) + " °F)", false],
    ["Orbital period", fmt(planet.orbital_period_days) + " days ("
                       + planet.orbital_period_years + " yr)", true],
    ["Density", fmt(planet.density_kg_m3) + " kg/m³", true],
    ["Surface gravity", planet.surface_gravity_m_s2 + " m/s² ("
                        + planet.gravity_vs_earth + " × Earth)", true],
    ["Escape velocity", planet.escape_velocity_km_s + " km/s", true],
    ["Moons", fmt(planet.moons), false]
  ];

  const bodyHtml = rows.map(function (row) {
    const cls = row[2] ? ' class="derived"' : "";
    return "<tr><th scope=\"row\">" + esc(row[0]) + "</th>"
         + "<td" + cls + ">" + esc(row[1]) + "</td></tr>";
  }).join("");

  document.getElementById("planetCard").innerHTML =
      '<img src="' + esc(meta.image) + '" alt="' + esc(planet.name) + '" '
    +     'loading="lazy" '
    +     'onerror="this.style.visibility=\'hidden\'">'
    + "<div>"
    +   "<h3>" + esc(planet.name) + "</h3>"
    +   '<p class="planet-meta">'
    +     '<span class="tag">' + esc(planet.classification) + "</span>"
    +     '<span class="tag">Planet ' + planet.order + "</span>"
    +   "</p>"
    +   '<p class="blurb">' + esc(meta.blurb) + "</p>"
    +   '<table class="stat-table">'
    +     "<caption>Values in bold are calculated by <code>analysis.py</code> "
    +     "from mass and radius.</caption>"
    +     "<tbody>" + bodyHtml + "</tbody>"
    +   "</table>"
    + "</div>";

  // Keep the big table's highlight in step with the dropdown.
  document.querySelectorAll("#allTable tbody tr").forEach(function (tr) {
    tr.classList.toggle("is-selected", tr.dataset.planet === planet.name);
  });
}

/* --------------------------------------------------------------------------
   8. Render: the all-planets table (sortable)
   -------------------------------------------------------------------------- */

let sortState = { key: "order", asc: true };

function renderTable(planets) {
  const table = document.getElementById("allTable");

  const sorted = planets.slice().sort(function (a, b) {
    const va = a[sortState.key];
    const vb = b[sortState.key];
    if (va < vb) return sortState.asc ? -1 : 1;
    if (va > vb) return sortState.asc ? 1 : -1;
    return 0;
  });

  // --- head ---
  table.tHead.innerHTML = "<tr>" + COLUMNS.map(function (col) {
    const active = sortState.key === col.key;
    const arrow = active ? (sortState.asc ? " ▲" : " ▼") : "";
    return '<th tabindex="0" role="button" data-key="' + col.key + '"'
         + ' aria-sort="' + (active ? (sortState.asc ? "ascending" : "descending") : "none") + '"'
         + (col.derived ? ' class="derived-key"' : "") + ">"
         + esc(col.label) + '<span class="arrow">' + arrow + "</span></th>";
  }).join("") + "</tr>";

  // --- body ---
  table.tBodies[0].innerHTML = sorted.map(function (p) {
    const cells = COLUMNS.map(function (col) {
      const raw = p[col.key];
      if (col.key === "name") {
        return '<td class="planet-name">' + esc(raw) + "</td>";
      }
      const classes = [];
      if (col.derived) classes.push("derived");
      if (col.key === "avg_temp_c") classes.push(tempClass(raw));
      const attr = classes.filter(Boolean).length
        ? ' class="' + classes.filter(Boolean).join(" ") + '"'
        : "";
      return "<td" + attr + ">" + esc(fmt(raw)) + "</td>";
    }).join("");
    return '<tr data-planet="' + esc(p.name) + '">' + cells + "</tr>";
  }).join("");

  // Sorting: click or keyboard on a heading.
  table.tHead.querySelectorAll("th").forEach(function (th) {
    function activate() {
      const key = th.dataset.key;
      // New column starts descending for numbers, ascending for text.
      if (sortState.key === key) {
        sortState.asc = !sortState.asc;
      } else {
        const col = COLUMNS.find(function (c) { return c.key === key; });
        sortState = { key: key, asc: col.type === "text" };
      }
      renderTable(planets);
      syncSelection();
    }
    th.addEventListener("click", activate);
    th.addEventListener("keydown", function (e) {
      if (e.key === "Enter" || e.key === " ") { e.preventDefault(); activate(); }
    });
  });

  // Clicking a row moves the dropdown to that planet.
  table.tBodies[0].querySelectorAll("tr").forEach(function (tr) {
    tr.addEventListener("click", function () {
      const select = document.getElementById("planetSelect");
      select.value = tr.dataset.planet;
      select.dispatchEvent(new Event("change"));
    });
  });
}

function syncSelection() {
  const name = document.getElementById("planetSelect").value;
  document.querySelectorAll("#allTable tbody tr").forEach(function (tr) {
    tr.classList.toggle("is-selected", tr.dataset.planet === name);
  });
}

/* --------------------------------------------------------------------------
   9. Render: the correlation finding
   -------------------------------------------------------------------------- */

function renderCorrelation(correlation, summary) {
  const outliers = (correlation.trend_breakers || []).map(function (o) {
    return '<p class="outlier"><strong>Trend breaker:</strong> ' + esc(o.note)
         + ". A thick carbon-dioxide atmosphere traps heat, so distance alone "
         + "does not decide temperature.</p>";
  }).join("");

  const tempStat = (summary.metrics || []).find(function (m) {
    return m.metric === "Average temperature";
  });

  const spread = tempStat
    ? "<p>Across the eight planets the average temperature ranges from "
      + esc(fmt(tempStat.min.value)) + " °C on " + esc(tempStat.min.planet)
      + " to " + esc(fmt(tempStat.max.value)) + " °C on " + esc(tempStat.max.planet)
      + ", with a mean of " + esc(fmt(tempStat.mean)) + " °C.</p>"
    : "";

  document.getElementById("correlation").innerHTML =
      '<p><span class="r-value">r = ' + esc(correlation.pearson_r) + "</span></p>"
    + "<p>Pearson correlation between distance from the Sun and average "
    + "temperature: a <strong>" + esc(correlation.interpretation) + "</strong>.</p>"
    + spread
    + outliers;
}

/* --------------------------------------------------------------------------
   10. Dark-mode toggle
   -------------------------------------------------------------------------- */

function setupThemeToggle() {
  const btn = document.getElementById("themeToggle");
  if (!btn) return;
  const root = document.documentElement;   // <html>; matches the CSS + head script

  function sync() {
    const isDark = root.classList.contains("dark");
    btn.textContent = isDark ? "Light mode" : "Dark mode";
    btn.setAttribute("aria-pressed", String(isDark));
  }

  btn.addEventListener("click", function () {
    const isDark = root.classList.toggle("dark");
    try { localStorage.setItem("theme", isDark ? "dark" : "light"); } catch (e) {}
    sync();
  });

  sync();   // label the button to match the theme applied by the head script
}

function setupColorToggle() {
  const btn = document.getElementById("colorToggle");
  if (!btn) return;
  const root = document.documentElement;

  function sync() {
    const inColor = root.classList.contains("color-images");
    btn.textContent = inColor ? "Grayscale images" : "Color images";
    btn.setAttribute("aria-pressed", String(inColor));
  }

  btn.addEventListener("click", function () {
    const inColor = root.classList.toggle("color-images");
    try { localStorage.setItem("images", inColor ? "color" : "grayscale"); } catch (e) {}
    sync();
  });

  sync();   // label to match whatever the head script already applied
}

/* --------------------------------------------------------------------------
   11. Start up
   -------------------------------------------------------------------------- */

async function init() {
  setupThemeToggle();              // wire this first so it works immediately,
                                   // without waiting on the data fetch
  setupColorToggle();
  const data = await loadData();
  const planets = data.planets;

  // Build the dropdown from the data so the two can never disagree.
  const select = document.getElementById("planetSelect");
  select.innerHTML = planets
    .slice()
    .sort(function (a, b) { return a.order - b.order; })
    .map(function (p) {
      return '<option value="' + esc(p.name) + '">'
           + p.order + ". " + esc(p.name) + "</option>";
    }).join("");

  const byName = {};
  planets.forEach(function (p) { byName[p.name] = p; });

  select.addEventListener("change", function () {
    renderPlanetCard(byName[this.value]);
  });

  renderTable(planets);
  select.value = "Earth";           // a familiar starting point
  renderPlanetCard(byName["Earth"]);
  renderCorrelation(data.correlation, data.summary);
}

document.addEventListener("DOMContentLoaded", init);
