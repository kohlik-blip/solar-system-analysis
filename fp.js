// Thousands separators, but leave small decimals alone.
function fmt(value) {
  if (typeof value !== "number") return value;
  return Math.abs(value) >= 1000
    ? value.toLocaleString("en-US")
    : String(value);
}

// Colour temperature values so hot and cold read at a glance.
function tempClass(celsius) {
  if (celsius > 100) return "temp-hot";
  if (celsius < -50) return "temp-cold";
  return "";
}

// Escape text before it goes anywhere near innerHTML.
function esc(text) {
  return String(text).replace(/[&<>"']/g, function (ch) {
    return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[ch];
  });
}

/* --------------------------------------------------------------------------
   6. Load the data (API first, offline second)
   -------------------------------------------------------------------------- */

async function loadData() {
  const badge = document.getElementById("dataSource");

  try {
    // AbortController stops the page hanging if nothing is listening.
    const controller = new AbortController();
    const timer = setTimeout(function () { controller.abort(); }, 2500);

    const [planets, summary, correlation] = await Promise.all([
      fetch(API_BASE + "/api/planets",              { signal: controller.signal }).then(checkOk),
      fetch(API_BASE + "/api/analysis/summary",     { signal: controller.signal }).then(checkOk),
      fetch(API_BASE + "/api/analysis/correlation", { signal: controller.signal }).then(checkOk)
    ]);

    clearTimeout(timer);
    badge.textContent = "Live data from the Flask API (app.py)";
    badge.className = "badge badge-live";
    return { planets: planets, summary: summary, correlation: correlation };

  } catch (err) {
    badge.textContent = "Offline mode — using saved analysis.py output. "
                      + "Run “python3 app.py” for live API data.";
    badge.className = "badge badge-offline";
    return OFFLINE_DATA;
  }
}

function checkOk(response) {
  if (!response.ok) throw new Error("HTTP " + response.status);
  return response.json();
}

